// Generates dist/tokens.css (raw custom properties, light + dark) and
// dist/theme.css (Tailwind v4 @theme block that maps utilities onto those vars).
// Runs on Node's built-in TypeScript type stripping: `node scripts/build-css.ts`.
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  breakpoints,
  colorScales,
  fontStacks,
  motion,
  radii,
  shadows,
  typeScale,
} from '../src/index.ts'

const here = dirname(fileURLToPath(import.meta.url))
const outDir = resolve(here, '../dist')
mkdirSync(outDir, { recursive: true })

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`)

const colorVars = (scheme: 'light' | 'dark') =>
  Object.entries(colorScales[scheme])
    .map(([k, v]) => `  --${kebab(k)}: ${v};`)
    .join('\n')

const tokensCss = `/* Generated by @elevate/tokens — do not edit by hand. */
:root {
  color-scheme: light dark;
${colorVars('light')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${colorVars('dark')}
  }
}

:root[data-theme="dark"] {
${colorVars('dark')}
}
`

const colorTheme = Object.keys(colorScales.light)
  .map((k) => `  --color-${kebab(k)}: var(--${kebab(k)});`)
  .join('\n')

const textTheme = Object.entries(typeScale)
  .map(([k, v]) => {
    const name = kebab(k)
    const lines = [
      `  --text-${name}: ${v.size}px;`,
      `  --text-${name}--line-height: ${v.lineHeight}px;`,
      `  --text-${name}--font-weight: ${v.weight};`,
    ]
    if ('letterSpacing' in v && v.letterSpacing) {
      lines.push(`  --text-${name}--letter-spacing: ${v.letterSpacing}em;`)
    }
    return lines.join('\n')
  })
  .join('\n')

const radiusTheme = Object.entries(radii)
  .map(([k, v]) => `  --radius-${k}: ${v}px;`)
  .join('\n')

const breakpointTheme = Object.entries(breakpoints)
  .map(([k, v]) => `  --breakpoint-${k}: ${v}px;`)
  .join('\n')

const themeCss = `/* Generated by @elevate/tokens — do not edit by hand. */
@import "./tokens.css";

@theme inline {
  --color-*: initial;
${colorTheme}
  --color-white: #ffffff;
  --color-black: #000000;
  --color-transparent: transparent;
  --color-current: currentColor;

  --font-display: ${fontStacks.display};
  --font-sans: ${fontStacks.text};
  --font-mono: ${fontStacks.mono};

${textTheme}

  --radius-*: initial;
${radiusTheme}

  --shadow-float: ${shadows.float.css};

  --breakpoint-*: initial;
${breakpointTheme}

  --ease-elevate: ${motion.easing};
  --animate-rise: rise ${motion.duration.base}ms ${motion.easing} both;

  @keyframes rise {
    from { opacity: 0; transform: translateY(${motion.rise}px); }
    to { opacity: 1; transform: translateY(0); }
  }
}
`

writeFileSync(resolve(outDir, 'tokens.css'), tokensCss)
writeFileSync(resolve(outDir, 'theme.css'), themeCss)
console.log('tokens: wrote dist/tokens.css and dist/theme.css')
