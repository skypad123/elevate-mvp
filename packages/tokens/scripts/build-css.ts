// Generates:
//   dist/tokens.css          raw custom properties, light + dark (Atelier)
//   dist/theme.css           Tailwind v4 @theme block that maps utilities onto those vars
//   dist/portal-<id>.css     per-portal overrides of the same vars, same selectors
// Runs on Node's built-in TypeScript type stripping: `node scripts/build-css.ts`.
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  breakpoints,
  colorScales,
  fontStacks,
  motion,
  portalPalettes,
  radii,
  shadows,
  typeScale,
} from '../src/index.ts'

const here = dirname(fileURLToPath(import.meta.url))
const outDir = resolve(here, '../dist')
mkdirSync(outDir, { recursive: true })

const header = '/* Generated by @elevate/tokens — do not edit by hand. */\n'

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`)

const colorVars = (scale: Record<string, string>, indent = '  ') =>
  Object.entries(scale)
    .map(([k, v]) => `${indent}--${kebab(k)}: ${v};`)
    .join('\n')

/**
 * The three selector blocks every colour file uses. Keeping them identical means a portal file
 * imported after tokens.css wins purely by source order, in light, OS-dark and forced themes.
 *
 * `system` preference = no data-theme attribute; `light`/`dark` = data-theme set by the app.
 * The forced blocks also pin `color-scheme` so native controls and scrollbars follow the choice.
 */
const schemeBlocks = (
  light: Record<string, string>,
  dark: Record<string, string>,
  { rootExtra = '', forceColorScheme = false } = {},
) => `:root {${rootExtra}
${colorVars(light)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${colorVars(dark, '    ')}
  }
}
${forceColorScheme ? '\n:root[data-theme="light"] {\n  color-scheme: light;\n}\n' : ''}
:root[data-theme="dark"] {${forceColorScheme ? '\n  color-scheme: dark;' : ''}
${colorVars(dark)}
}
`

const tokensCss =
  header +
  schemeBlocks(colorScales.light, colorScales.dark, {
    rootExtra: '\n  color-scheme: light dark;',
    forceColorScheme: true,
  })

const colorTheme = Object.keys(colorScales.light)
  .map((k) => `  --color-${kebab(k)}: var(--${kebab(k)});`)
  .join('\n')

const textTheme = Object.entries(typeScale)
  .map(([k, v]) => {
    const name = kebab(k)
    const lines = [
      `  --text-${name}: ${v.size}px;`,
      `  --text-${name}--line-height: ${v.lineHeight}px;`,
      `  --text-${name}--font-weight: ${v.weight};`,
    ]
    if ('letterSpacing' in v && v.letterSpacing) {
      lines.push(`  --text-${name}--letter-spacing: ${v.letterSpacing}em;`)
    }
    return lines.join('\n')
  })
  .join('\n')

const radiusTheme = Object.entries(radii)
  .map(([k, v]) => `  --radius-${k}: ${v}px;`)
  .join('\n')

const breakpointTheme = Object.entries(breakpoints)
  .map(([k, v]) => `  --breakpoint-${k}: ${v}px;`)
  .join('\n')

const themeCss = `${header}@import "./tokens.css";

@theme inline {
  --color-*: initial;
${colorTheme}
  --color-white: #ffffff;
  --color-black: #000000;
  --color-transparent: transparent;
  --color-current: currentColor;

  --font-display: ${fontStacks.display};
  --font-sans: ${fontStacks.text};
  --font-mono: ${fontStacks.mono};

${textTheme}

  --radius-*: initial;
${radiusTheme}

  --shadow-float: ${shadows.float.css};

  --breakpoint-*: initial;
${breakpointTheme}

  --ease-elevate: ${motion.easing};
  --animate-rise: rise ${motion.duration.base}ms ${motion.easing} both;

  @keyframes rise {
    from { opacity: 0; transform: translateY(${motion.rise}px); }
    to { opacity: 1; transform: translateY(0); }
  }
}
`

writeFileSync(resolve(outDir, 'tokens.css'), tokensCss)
writeFileSync(resolve(outDir, 'theme.css'), themeCss)

const written = ['tokens.css', 'theme.css']
for (const [id, palette] of Object.entries(portalPalettes)) {
  const file = `portal-${id}.css`
  writeFileSync(
    resolve(outDir, file),
    `${header}/* Import after theme.css to re-colour the ${id} portal. */\n${schemeBlocks(palette.light, palette.dark)}`,
  )
  written.push(file)
}
console.log(`tokens: wrote ${written.map((f) => `dist/${f}`).join(', ')}`)
